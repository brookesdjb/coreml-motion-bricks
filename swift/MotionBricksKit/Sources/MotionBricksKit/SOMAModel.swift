import CoreML
import Foundation

/// Which CoreML compute units to allow. `.cpuAndNeuralEngine` is the production choice.
public enum ComputeChoice: String, CaseIterable, Identifiable, Sendable {
    case cpuAndNeuralEngine = "CPU + Neural Engine"
    case cpuAndGPU = "CPU + GPU"
    case cpuOnly = "CPU only"
    case all = "All"

    public var id: String { rawValue }
    public var units: MLComputeUnits {
        switch self {
        case .cpuAndNeuralEngine: .cpuAndNeuralEngine
        case .cpuAndGPU: .cpuAndGPU
        case .cpuOnly: .cpuOnly
        case .all: .all
        }
    }
}

/// One network input, matching the batch-1 SOMA package (see cmb/convert.py INPUT_NAMES).
public struct SOMAInput: Sendable {
    public var globalRootValues: [Float]      // [1, 8, 5]
    public var hasGlobalRootValues: [Int32]   // [1, 8]
    public var localRootValues: [Float]       // [1, 8, 4]
    public var hasLocalRootValues: [Int32]    // [1, 8]
    public var localPoses: [Float]            // [1, 8, 267]
    public var hasLocalPoses: [Int32]         // [1, 8]
    public var allowedPredNumTokens: [Int32]  // [1, 11]

    public init(globalRootValues: [Float], hasGlobalRootValues: [Int32], localRootValues: [Float],
                hasLocalRootValues: [Int32], localPoses: [Float], hasLocalPoses: [Int32],
                allowedPredNumTokens: [Int32]) {
        self.globalRootValues = globalRootValues
        self.hasGlobalRootValues = hasGlobalRootValues
        self.localRootValues = localRootValues
        self.hasLocalRootValues = hasLocalRootValues
        self.localPoses = localPoses
        self.hasLocalPoses = hasLocalPoses
        self.allowedPredNumTokens = allowedPredNumTokens
    }
}

/// Network output: up to 64 frames of 366 values, of which the first `4 * numTokens` are valid.
public struct SOMAOutput: Sendable {
    public static let frames = 64, channels = 366
    public var motion: [Float]  // [64, 366]
    public var numTokens: Int
    public var validFrames: Int { min(Self.frames, 4 * numTokens) }
}

/// The batch-1 SOMA CoreML model with typed inputs and outputs.
public final class SOMAModel: @unchecked Sendable {
    public let model: MLModel
    public let compiledURL: URL
    public let computeChoice: ComputeChoice
    public private(set) var loadSeconds: Double

    /// Loads an `.mlpackage` (compiled on the fly) or an already compiled `.mlmodelc`.
    public init(url: URL, compute: ComputeChoice = .cpuAndNeuralEngine) async throws {
        let t = ContinuousClock.now
        compiledURL = url.pathExtension == "mlmodelc" ? url : try await MLModel.compileModel(at: url)
        let config = MLModelConfiguration()
        config.computeUnits = compute.units
        model = try await MLModel.load(contentsOf: compiledURL, configuration: config)
        computeChoice = compute
        loadSeconds = (ContinuousClock.now - t).seconds
    }

    /// Runs one prediction; `seconds` covers only the CoreML call.
    public func predict(_ input: SOMAInput) throws -> (output: SOMAOutput, seconds: Double) {
        let provider = try MLDictionaryFeatureProvider(dictionary: [
            "global_root_values": MLMultiArray(input.globalRootValues, shape: [1, 8, 5]),
            "has_global_root_values": MLMultiArray(input.hasGlobalRootValues, shape: [1, 8]),
            "local_root_values": MLMultiArray(input.localRootValues, shape: [1, 8, 4]),
            "has_local_root_values": MLMultiArray(input.hasLocalRootValues, shape: [1, 8]),
            "local_poses": MLMultiArray(input.localPoses, shape: [1, 8, 267]),
            "has_local_poses": MLMultiArray(input.hasLocalPoses, shape: [1, 8]),
            "allowed_pred_num_tokens": MLMultiArray(input.allowedPredNumTokens, shape: [1, 11]),
        ])
        let t = ContinuousClock.now
        let out = try model.prediction(from: provider)
        let seconds = (ContinuousClock.now - t).seconds
        // Output names are generated by the converter; pick the tensors by size as cmb/engine.py split_outputs does.
        var motion: MLMultiArray?, tokens: MLMultiArray?
        for name in out.featureNames {
            guard let a = out.featureValue(for: name)?.multiArrayValue else { continue }
            if a.count > 100 { motion = a } else if a.count == 1 { tokens = a }
        }
        guard let motion, let tokens else { throw SOMAError.unexpectedOutputs(Array(out.featureNames)) }
        return (SOMAOutput(motion: motion.floats(), numTokens: tokens[0].intValue), seconds)
    }
}

public enum SOMAError: Error, CustomStringConvertible {
    case unexpectedOutputs([String])
    case badFeeds(String)
    public var description: String {
        switch self {
        case .unexpectedOutputs(let n): "unexpected model outputs: \(n)"
        case .badFeeds(let s): "bad feeds: \(s)"
        }
    }
}

extension MLMultiArray {
    convenience init<T: MLShapedArrayScalar>(_ values: [T], shape: [Int]) {
        self.init(MLShapedArray<T>(scalars: values, shape: shape))
    }

    /// Contiguous float copy whatever the storage type (the Neural Engine model returns fp16).
    func floats() -> [Float] {
        switch dataType {
        case .float16: MLShapedArray<Float16>(converting: self).scalars.map(Float.init)
        case .float32: MLShapedArray<Float>(converting: self).scalars
        case .double: MLShapedArray<Double>(converting: self).scalars.map(Float.init)
        default: (0..<count).map { self[$0].floatValue }
        }
    }
}

extension Duration {
    var seconds: Double { Double(components.seconds) + Double(components.attoseconds) * 1e-18 }
}
